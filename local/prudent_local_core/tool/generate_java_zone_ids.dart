// Writes lib/src/plans/java_zone_ids.dart from test/golden/plans.json: the JVM's own
// ZoneId.getAvailableZoneIds() (unit 6b, ADR-119).
//
// Run from the package root after GoldenVectorsTest regenerated the golden file:
//
//   dart run tool/generate_java_zone_ids.dart
//
// test/plans/plan_zones_test.dart fails, naming this command, whenever the committed file is not
// what this writes.
import 'dart:convert';
import 'dart:io';

void main() {
  final golden =
      jsonDecode(File('test/golden/plans.json').readAsStringSync()) as Map<String, Object?>;
  final ids = (golden['zoneIds']! as List<Object?>).cast<String>();
  File('lib/src/plans/java_zone_ids.dart').writeAsStringSync(render(ids));
}

String render(List<String> ids) {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_java_zone_ids.dart from test/golden/plans.json.')
    ..writeln('// Never edit by hand: regenerate the golden file on the server, then run that tool.')
    ..writeln()
    ..writeln("part of 'plan_zones.dart';")
    ..writeln()
    ..writeln('/// Every id `ZoneId.getAvailableZoneIds()` answers on the server\'s JDK: ${ids.length} ids, the set')
    ..writeln('/// a plan may name as its time zone (`RecurrenceRule.parseZone`, rule 6.31), less')
    ..writeln('/// `PlanZones.unsupported`. A fixed offset such as `+02:00` or `Z` is not one of them.')
    ..writeln('const Set<String> _javaZoneIds = {');
  for (final id in ids) {
    out.writeln("  '$id',");
  }
  out.writeln('};');
  return out.toString();
}

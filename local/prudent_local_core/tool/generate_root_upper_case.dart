// Writes lib/src/imports/java_root_upper_case.dart from test/golden/import_fingerprints.json, the
// JVM's own String.toUpperCase(Locale.ROOT) of every code point it changes (unit 8a, ADR-091).
//
// Run from the package root after GoldenVectorsTest regenerated the golden file:
//
//   dart run tool/generate_root_upper_case.dart
//
// test/imports/row_fingerprints_test.dart fails, naming this command, whenever the committed table
// is not the golden file's.
import 'dart:convert';
import 'dart:io';

void main() {
  final golden =
      jsonDecode(File('test/golden/import_fingerprints.json').readAsStringSync())
          as Map<String, Object?>;
  final table = (golden['rootUpperCase']! as List<Object?>).cast<List<Object?>>();
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_root_upper_case.dart from test/golden/import_fingerprints.json.')
    ..writeln('// Never edit by hand: regenerate the golden file on the server, then run that tool.')
    ..writeln()
    ..writeln("part of 'row_fingerprints.dart';")
    ..writeln()
    ..writeln('/// Java `String.toUpperCase(Locale.ROOT)` of every code point it changes, from the JDK the')
    ..writeln('/// server runs on: ${table.length} entries. Every other code point upper-cases to itself.')
    ..writeln('const Map<int, String> _javaRootUpperCase = {');
  for (final entry in table) {
    final codePoint = entry[0]! as int;
    final upper = entry[1]! as String;
    final escaped = upper.runes.map((r) => '\\u{${r.toRadixString(16).toUpperCase()}}').join();
    out.writeln("  0x${codePoint.toRadixString(16).toUpperCase().padLeft(4, '0')}: '$escaped',");
  }
  out.writeln('};');
  File('lib/src/imports/java_root_upper_case.dart').writeAsStringSync(out.toString());
  stdout.writeln('wrote ${table.length} entries');
}

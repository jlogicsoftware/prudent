/**
 * The golden vectors of Prudent Local's domain core (unit 3 of {@code
 * docs/plans/PRUDENT-LOCAL-PLAN.md}, ADR-107): what the server's own rule methods answer for a
 * fixed set of inputs, written to {@code local/prudent_local_core/test/golden/*.json} and run by
 * the Dart tests there, so that the Dart port is held to the Java implementation and not to a
 * reading of it.
 *
 * <p><strong>This test fails when a committed file is not what the server answers today</strong> —
 * a rule changed on the server and the Local port has not followed. Regenerate with
 *
 * <pre>(cd server &amp;&amp; ./mvnw -B test -Dtest=GoldenVectorsTest -Dprudent.golden.write=true)</pre>
 *
 * then read the diff and change the Dart port until {@code dart test} in {@code
 * local/prudent_local_core} passes. Writing the files never passes silently in CI: the property is
 * only set by that command.
 *
 * <p>A plain JUnit test, not a {@code @QuarkusTest}: every rule here is a static method, so it runs
 * in a second without Docker. The currency table and the white-space tables are the running JDK's —
 * which is the point: they are what the server accepts, and a JDK update that changes ISO-4217 is a
 * change Local must follow.
 */

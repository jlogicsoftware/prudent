  @Test
  void currencies() {
    Map<String, Object> out = header("Rule 3.2: ISO-4217 codes, trimmed and upper-cased (Currencies.java).");
    List<Object> codes = new ArrayList<>();
    for (char a = 'A'; a <= 'Z'; a++) {
      for (char b = 'A'; b <= 'Z'; b++) {
        for (char c = 'A'; c <= 'Z'; c++) {
          String code = "" + a + b + c;
          if (Currencies.isValid(code)) {
            codes.add(code);
          }
        }
      }
    }
    out.put("iso4217", codes);

    // Every code point, other than a-z and A-Z, that String.toUpperCase(Locale.ROOT) turns into
    // ASCII capitals only. These are the only non-ASCII characters that can end in a valid code
    // ("ınr" is INR, "ßp" is SSP), so the Dart port needs exactly this table and no more.
    List<Object> foldsToAscii = new ArrayList<>();
    Pattern capitals = Pattern.compile("[A-Z]+");
    for (int cp = 0; cp <= Character.MAX_CODE_POINT; cp++) {
      if ((cp >= 'a' && cp <= 'z') || (cp >= 'A' && cp <= 'Z')) {
        continue;
      }
      String upper = Character.toString(cp).toUpperCase(Locale.ROOT);
      if (capitals.matcher(upper).matches()) {
        Map<String, Object> entry = new LinkedHashMap<>();
        entry.put("codePoint", cp);
        entry.put("upper", upper);
        foldsToAscii.add(entry);
      }
    }
    out.put("rootUpperCaseToAsciiCapitals", foldsToAscii);

    List<Object> cases = new ArrayList<>();
    for (String input : HostileText.currencies()) {
      Map<String, Object> entry = new LinkedHashMap<>();
      entry.put("input", input);
      entry.put("normalize", Currencies.normalize(input));
      entry.put("isValid", Currencies.isValid(input));
      entry.put("parse", attempt(() -> BudgetRulesAccess.parseCurrency(input)));
      cases.add(entry);
    }
    out.put("cases", cases);
    check("currencies.json", out);
  }

  @Test
  void text() {
    Map<String, Object> out =
        header(
            "Rules 3.7 and 3.8: trim (chars <= U+0020), strip and isBlank (Character.isWhitespace),"
                + " code points (the 500-character note, finding F-04), UTF-8 as Java encodes it.");
    out.put("javaWhitespace", ranges(cp -> Character.isWhitespace(cp)));
    Pattern unicodeSpace = Pattern.compile("(?U)\\s");
    out.put(
        "unicodeWhiteSpace", ranges(cp -> unicodeSpace.matcher(Character.toString(cp)).matches()));
    List<Object> cases = new ArrayList<>();
    for (String input : HostileText.general()) {
      Map<String, Object> entry = new LinkedHashMap<>();
      entry.put("input", input);
      if (input != null) {
        entry.put("trim", input.trim());
        entry.put("strip", input.strip());
        entry.put("isBlank", input.isBlank());
        entry.put("codePoints", input.codePointCount(0, input.length()));
        entry.put("utf8", HexFormat.of().formatHex(input.getBytes(StandardCharsets.UTF_8)));
        // The note rule exactly as GoalAllocationResource and BudgetCarryOverResetResource write it.
        String stripped = input.strip();
        entry.put("stripNoteWithin500", stripped.codePointCount(0, stripped.length()) <= 500);
        // ... and as ImportWorkflow writes it (trim, then the same count).
        String trimmed = input.trim();
        entry.put("trimNoteWithin500", trimmed.codePointCount(0, trimmed.length()) <= 500);
      }
      cases.add(entry);
    }
    out.put("cases", cases);
    check("text.json", out);
  }


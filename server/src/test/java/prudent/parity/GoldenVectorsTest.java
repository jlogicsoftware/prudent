  /**
   * The answer of a rule method: {@code {"ok": value}}, or the refusal it threw — {@code
   * {"refused": status}} for a {@link PrudentException}, {@code {"error": class}} for anything else.
   * Nothing is caught that a rule method does not deliberately throw: an unexpected exception type
   * is still written, and the Dart side must then answer the same.
   */
  private static Map<String, Object> attempt(Supplier<String> rule) {
    Map<String, Object> result = new LinkedHashMap<>();
    try {
      result.put("ok", rule.get());
    } catch (PrudentException refused) {
      result.put("refused", refused.status().getStatusCode());
    } catch (RuntimeException failed) {
      result.put("error", failed.getClass().getSimpleName());
    }
    return result;
  }

  /** A number, or the class of the exception the rule method threw. */
  private static Object answer(Supplier<Long> rule) {
    try {
      return rule.get();
    } catch (RuntimeException failed) {
      return failed.getClass().getSimpleName();
    }
  }

  private static Object exact(Supplier<Long> operation) {
    try {
      return operation.get();
    } catch (ArithmeticException overflow) {
      return "overflow";
    }
  }

  private interface CodePointTest {
    boolean test(int cp);
  }

  /** Inclusive ranges {@code [first, last]} of the code points a predicate holds for. */
  private static List<Object> ranges(CodePointTest predicate) {
    List<Object> out = new ArrayList<>();
    int start = -1;
    for (int cp = 0; cp <= Character.MAX_CODE_POINT + 1; cp++) {
      boolean in = cp <= Character.MAX_CODE_POINT && predicate.test(cp);
      if (in && start < 0) {
        start = cp;
      } else if (!in && start >= 0) {
        out.add(List.of(start, cp - 1));
        start = -1;
      }
    }
    return out;
  }

  private static void check(String name, Map<String, Object> content) {
    if (!FILES.contains(name)) {
      throw new IllegalStateException(name + " is written but not listed in FILES");
    }
    String expected = GoldenJson.write(content);
    Path file = DIR.resolve(name);
    try {
      if (WRITE) {
        Files.createDirectories(DIR);
        Files.writeString(file, expected, StandardCharsets.US_ASCII);
        return;
      }
      assertTrue(
          Files.exists(file),
          file.toAbsolutePath() + " is missing. Generate it: (cd server && ./mvnw -B test"
              + " -Dtest=GoldenVectorsTest -Dprudent.golden.write=true)");
      String actual = Files.readString(file, StandardCharsets.US_ASCII);
      if (!actual.equals(expected)) {
        fail(
            name + " is not what the server's rules answer today: a server rule changed and Prudent"
                + " Local's port has not followed (ADR-107). Regenerate with (cd server && ./mvnw -B"
                + " test -Dtest=GoldenVectorsTest -Dprudent.golden.write=true), read the diff, and"
                + " change local/prudent_local_core until its dart test passes."
                + ("plans.json".equals(name)
                    ? " plans.json also holds the JDK's zone ids: after regenerating it, run"
                        + " (cd local/prudent_local_core && dart run tool/generate_java_zone_ids.dart)"
                        + " to rewrite lib/src/plans/java_zone_ids.dart, and commit both. If only"
                        + " zoneIds differ, the JDK that ran this has a different tzdata than the one"
                        + " that wrote the file: that is a new zone or a removed one, to follow, not"
                        + " noise."
                    : ""));
      }
    } catch (IOException io) {
      throw new IllegalStateException("cannot read or write " + file.toAbsolutePath(), io);
    }
  }
